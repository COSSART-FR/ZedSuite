function hexBytes(hex: string): number[] {
  const out: number[] = [];
  for (let i = 0; i < hex.length; i += 2) out.push(parseInt(hex.slice(i, i + 2), 16));
  return out;
}

function ascii(data: Uint8Array, at: number, len: number): string {
  let s = '';
  for (let i = 0; i < len && at + i < data.length; i++) s += String.fromCharCode(data[at + i]);
  return s;
}

function containsAscii(data: Uint8Array, text: string): boolean {
  const codes = Array.from(text, (c) => c.charCodeAt(0));
  outer: for (let p = 0; p + codes.length <= data.length; p++) {
    for (let k = 0; k < codes.length; k++) if (data[p + k] !== codes[k]) continue outer;
    return true;
  }
  return false;
}

/** Le fichier est-il bien le logiciel 1037361858 ? */
export function isE46320d361858(data: Uint8Array): boolean {
  return (
    data.length === 0x100000 &&
    ascii(data, SW_OFFSET, SW_NUMBER.length) === SW_NUMBER &&
    containsAscii(data, FAMILY)
  );
}

function replay(data: Uint8Array, ranges: PatchRange[], label: string): BinaryPatch[] {
  if (!isE46320d361858(data)) return [];
  const patches: BinaryPatch[] = [];
  for (const [address, expectHex, writeHex] of ranges) {
    const expect = hexBytes(expectHex);
    for (let i = 0; i < expect.length; i++) {
      // Octets déjà différents : fichier modifié ou solution déjà appliquée.
      // Un patch partiel serait pire que pas de patch.
      if (data[address + i] !== expect[i]) return [];
    }
    patches.push({
      address,
      data: hexBytes(writeHex),
      description: `${label} @ 0x${address.toString(16).toUpperCase()}`,
    });
  }
  return patches;
}

